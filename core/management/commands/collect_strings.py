"""Write core/i18n_generated.py listing every form label, help text and static
choice label so `makemessages` extracts them.

Run before `makemessages`:
    python manage.py collect_strings && python manage.py makemessages -l zh_Hans ...
"""
import importlib
from pathlib import Path

from django import forms
from django.conf import settings
from django.core.management.base import BaseCommand
from django.forms.utils import pretty_name

FORM_MODULES = ["core.forms", "properties.forms", "deals.forms", "deadlines.forms",
                "checklists.forms", "commissions.forms", "imports.views"]
APPS = ["core", "crm", "properties", "deals", "documents", "deadlines", "checklists", "commissions", "imports"]


def _subclasses(cls):
    for sub in cls.__subclasses__():
        yield sub
        yield from _subclasses(sub)


class Command(BaseCommand):
    help = "Collect form and model labels for translation."

    def handle(self, *args, **kwargs):
        strings = set()

        def add(value):
            if value:
                text = str(value).strip()
                if text and any(c.isalpha() for c in text):
                    strings.add(text)

        for mod in FORM_MODULES:
            importlib.import_module(mod)
        for form_cls in _subclasses(forms.BaseForm):
            if not form_cls.__module__.split(".")[0] in APPS:
                continue
            for name, field in form_cls.base_fields.items():
                add(field.label if field.label is not None else pretty_name(name))
                add(field.help_text)
                if isinstance(field, forms.ChoiceField) and not isinstance(field, forms.ModelChoiceField):
                    try:
                        choices = list(field.choices)
                    except Exception:  # noqa: BLE001 - choices needing a database
                        continue
                    for value, label in choices:
                        if isinstance(label, (list, tuple)):
                            add(value)
                            for _v, lab in label:
                                add(lab)
                        else:
                            add(label)
        from deals.catalog import EVENT_CATALOG, TERM_CATALOG, TERM_CATEGORY_ORDER

        for label, *_rest in TERM_CATALOG.values():
            add(label)
        for label in EVENT_CATALOG.values():
            add(label)
        for cat in TERM_CATEGORY_ORDER:
            add(cat)
        add("Effective date")
        from properties.models import FACT_CATALOG

        for items in FACT_CATALOG.values():
            for _key, label in items:
                add(label)
        lines = ['"""Generated by `manage.py collect_strings` — do not edit."""',
                 "from django.utils.translation import gettext_noop as _", "", "STRINGS = ["]
        for s in sorted(strings):
            lines.append(f"    _({s!r}),")
        lines.append("]")
        out = Path(settings.BASE_DIR) / "core" / "i18n_generated.py"
        out.write_text("\n".join(lines) + "\n")
        self.stdout.write(f"Wrote {len(strings)} strings to {out}")
